"""Recorrido real en Edge, fase 1: QR -> aprobación -> cocina -> entrega -> caja, más tablet con PIN y reportes."""
from playwright.sync_api import sync_playwright, expect
from comun import APP, errores, api, contexto, login, shot, elegir_opciones, abrir_navegador, terminar

admin_token = api("/login", {"usuario": "admin.esquina", "password": "demo1234"})["token"]
token_mesa5 = next(q for q in api("/qr/list", {}, admin_token) if q["mesa"] == "Mesa 5")["url"].rsplit("/", 1)[1]

with sync_playwright() as p:
    browser = abrir_navegador(p)

    # 1. Cliente pide por QR con modificadores
    cliente = contexto(browser, 390, 844, mobile=True)
    cliente.goto(f"{APP}/q/{token_mesa5}")
    expect(cliente.get_by_text("Salón · Mesa 5")).to_be_visible()
    shot(cliente, "01-carta-celular")
    cliente.get_by_label("Agregar Hamburguesa clásica").click()
    expect(cliente.get_by_role("button", name="Falta: término de la carne")).to_be_disabled()
    cliente.get_by_role("dialog").get_by_role("button", name="Medio").click()
    cliente.get_by_role("dialog").get_by_role("button", name="Queso extra").click()
    shot(cliente, "02-opciones-celular")
    cliente.get_by_role("dialog").get_by_role("button", name="Agregar").click()
    cliente.get_by_label("Agregar Cerveza nacional").click()
    cliente.get_by_text("Ver pedido (2)").click()
    cliente.get_by_label("Indicación para Hamburguesa clásica").fill("sin cebolla")
    shot(cliente, "03-carrito-celular")
    cliente.get_by_role("button", name="Enviar pedido").click()
    cliente.wait_for_url("**/pedido/**")
    expect(cliente.get_by_text("El mesero confirmará tu pedido")).to_be_visible()

    # 2. Mesero aprueba; cocina y bar reciben por WebSocket
    mesero = contexto(browser, 1180, 820)
    login(mesero, "mesero.salon")
    mesero.wait_for_url("**/mesas")
    cocina = contexto(browser, 1280, 800)
    login(cocina, "cocina.esquina")
    cocina.wait_for_url("**/produccion/**")
    bar = contexto(browser, 1024, 768)
    login(bar, "bar.esquina")
    bar.wait_for_url("**/produccion/**")
    cocina.wait_for_timeout(800)
    mesero.get_by_role("button", name="Aprobar").first.click()
    expect(mesero.get_by_text("orden enviada a producción")).to_be_visible()

    expect(cocina.locator(".slip")).to_have_count(1, timeout=8000)
    expect(cocina.get_by_text("+ Queso extra")).to_be_visible()
    expect(cocina.get_by_text("sin cebolla")).to_be_visible()
    shot(cocina, "05-cocina-con-modificadores")
    cocina.get_by_role("button", name="Abrir").click()
    cocina.get_by_role("button", name="Despachar").click()
    bar.get_by_role("button", name="Abrir").click()
    bar.get_by_role("button", name="Despachar").click()

    # 3. Entrega y el mesero pide la cuenta
    mesero.reload()
    expect(mesero.get_by_role("heading", name="Para llevar a la mesa")).to_be_visible(timeout=8000)
    mesero.get_by_role("button", name="Entregado").first.click()
    expect(mesero.get_by_text("Entregado en Mesa 5")).to_be_visible()
    mesero.get_by_role("button", name="Mesa 5").click()
    mesero.wait_for_url("**/mesas/**")
    mesero.get_by_role("tab", name="En la mesa").click()
    mesero.get_by_role("button", name="Pedir la cuenta").click()
    expect(mesero.get_by_text("Cuenta pedida")).to_be_visible()
    shot(mesero, "06-tablet-cuenta-pedida")

    # 4. Orden en la tablet con modificador obligatorio
    mesero.get_by_role("link", name="Volver").click()
    expect(mesero.get_by_text("Pidió la cuenta")).to_be_visible()
    shot(mesero, "07-tablet-mesas")
    mesero.get_by_role("button", name="Mesa 2").click()
    mesero.wait_for_url("**/mesas/**")
    mesero.get_by_role("button", name="Hamburguesa doble").click()
    elegir_opciones(mesero, ["Tres cuartos", "Tocineta"])
    mesero.get_by_role("tab", name="Bebidas").click()
    mesero.get_by_role("button", name="Limonada natural").click()
    shot(mesero, "08-tablet-orden-con-opciones")
    mesero.get_by_role("button", name="Enviar a cocina").click()
    expect(mesero.get_by_text("enviada.")).to_be_visible()

    # 5. Caja: abrir turno y cobrar la Mesa 5 con pago mixto
    caja = contexto(browser, 1280, 860)
    login(caja, "caja.esquina")
    caja.goto(f"{APP}/caja")
    caja.get_by_label("Base en efectivo").fill("100000")
    caja.get_by_role("button", name="Abrir turno").click()
    expect(caja.get_by_text("Turno de Marta Caja")).to_be_visible()
    caja.get_by_role("button", name="Mesa 5").click()
    expect(caja.get_by_text("Pidió la cuenta").first).to_be_visible()
    caja.get_by_role("button", name="10 %").click()
    caja.wait_for_timeout(500)
    caja.get_by_role("button", name="Tarjeta (datáfono)").click()
    caja.locator(".pago").first.get_by_label("Valor").fill("20000")
    caja.get_by_role("group", name="Medio de pago").get_by_role("button", name="Efectivo").click()
    caja.locator(".pago").nth(1).get_by_role("button", name="$ 50.000").click()
    shot(caja, "09-caja-cobro-mixto")
    caja.get_by_role("button", name="Cobrar").click()
    expect(caja.get_by_text("Pagada · C-")).to_be_visible()
    expect(caja.get_by_text("Cambio:").first).to_be_visible()
    caja.get_by_role("button", name="Imprimir comprobante").click()
    shot(caja, "10-caja-pagada")
    caja.get_by_role("tab", name="Turno y jornada").click()
    expect(caja.get_by_text("Efectivo esperado en caja")).to_be_visible()
    shot(caja, "11-caja-turno")
    cliente.reload()
    expect(cliente.get_by_text("¡Buen provecho!")).to_be_visible()

    # 6. Tablet compartida: emparejar con código y entrar con PIN
    adm = contexto(browser, 1366, 860)
    login(adm, "admin.esquina")
    adm.goto(f"{APP}/admin/dispositivos")
    adm.get_by_role("button", name="Autorizar dispositivo").first.click()
    adm.fill("#d-nombre", "Tablet Salón")
    adm.get_by_role("button", name="Crear y ver código").click()
    codigo = adm.locator(".codigo .numero").inner_text().replace("Código de emparejamiento:", "").strip()
    shot(adm, "12-admin-codigo-dispositivo")
    carlos = next(u for u in api("/usuario/list", {}, admin_token) if u["usuario"] == "mesero.salon")
    api("/usuario/pin", {"usuario_id": carlos["id"], "pin": "4821"}, admin_token)

    tablet = contexto(browser, 1024, 768)
    tablet.goto(f"{APP}/dispositivo")
    tablet.fill("input[autocomplete=one-time-code]", codigo)
    tablet.get_by_role("button", name="Autorizar").click()
    expect(tablet.get_by_text("Escribe tu PIN")).to_be_visible()
    for digito in "4821":
        tablet.get_by_role("button", name=digito, exact=True).click()
    shot(tablet, "13-tablet-pin")
    tablet.get_by_role("button", name="Entrar").click()
    tablet.wait_for_url("**/mesas")
    expect(tablet.get_by_role("button", name="Cambiar de mesero")).to_be_visible()
    shot(tablet, "14-tablet-con-pin")
    tablet.get_by_role("button", name="Cambiar de mesero").click()
    tablet.wait_for_url("**/dispositivo")

    # 7. Administración: modificadores, horarios, reportes
    adm.goto(f"{APP}/admin/modificadores")
    expect(adm.get_by_role("cell", name="Término de la carne")).to_be_visible()
    shot(adm, "15-admin-modificadores")
    adm.goto(f"{APP}/admin/zonas")
    adm.get_by_role("button", name="Horario").first.click()
    adm.get_by_role("button", name="Igual todos los días").first.click()
    shot(adm, "16-admin-horario-zona")
    adm.keyboard.press("Escape")
    adm.goto(f"{APP}/admin")
    expect(adm.get_by_text("Ventas de hoy")).to_be_visible()
    shot(adm, "17-admin-hoy-dashboard")
    adm.goto(f"{APP}/admin/reportes")
    expect(adm.get_by_role("heading", name="Productos más vendidos")).to_be_visible()
    shot(adm, "18-reportes-hoy")
    adm.get_by_role("button", name="Últimos 7 días").click()
    expect(adm.get_by_text("Ventas por jornada")).to_be_visible()
    shot(adm, "19-reportes-semana")
    adm.get_by_role("link", name="Informe").first.click()
    expect(adm.get_by_text("Detalle por mesa")).to_be_visible()
    shot(adm, "20-informe-mesero")
    adm.goto(f"{APP}/admin/restaurante")
    expect(adm.get_by_role("heading", name="Medios de pago")).to_be_visible()
    shot(adm, "21-admin-configuracion")

    # 8. Celular
    movil = contexto(browser, 390, 844, mobile=True)
    login(movil, "caja.esquina")
    movil.goto(f"{APP}/caja")
    shot(movil, "22-caja-celular")
    movil.get_by_role("button", name="Mesa 2").click()
    shot(movil, "23-caja-celular-cobro")
    mesero_movil = contexto(browser, 390, 844, mobile=True)
    login(mesero_movil, "mesero.salon")
    mesero_movil.goto(f"{APP}/mi-informe")
    expect(mesero_movil.get_by_text("Mesas atendidas")).to_be_visible()
    shot(mesero_movil, "24-mi-informe-celular")
    adm_movil = contexto(browser, 390, 844, mobile=True)
    login(adm_movil, "admin.esquina")
    for ruta in ["admin", "admin/reportes", "admin/modificadores", "admin/dispositivos"]:
        adm_movil.goto(f"{APP}/{ruta}")
        adm_movil.wait_for_load_state("networkidle")
        shot(adm_movil, "25-celular-" + ruta.replace("/", "-"))

    browser.close()

print("ERRORES DE CONSOLA:", len(errores))
for e in errores:
    print(" -", e[:300])
